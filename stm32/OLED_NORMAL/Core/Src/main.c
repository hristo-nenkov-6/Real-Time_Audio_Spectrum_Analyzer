/* USER CODE BEGIN 4 */
void map_wave_to_ssd1306(uint16_t *buffer, uint8_t processed)
{
	if (processed == 1)
	{
		for (int i = 0; i < MEM_BUFFER_SIZE / 2 / DIVIDER; i++)
		{
			int sum = 0;

			for (int j = 0; j < DIVIDER; j++)
			{
				sum += buffer[ DIVIDER * i + j];
			}
			int real_y = (sum / DIVIDER) / 128;

			if (i > 0)
			{
			SSD1306_DrawLine(i - 1, prev_y, i, real_y, SSD1306_COLOR_WHITE);
			}
			prev_y = real_y;
		}
	}
	else if (processed == 2)
	{
		for (int i = MEM_BUFFER_SIZE / 2 / DIVIDER ; i < MEM_BUFFER_SIZE / DIVIDER ; i++)
		{
			int sum = 0;
			for (int j = 0; j < DIVIDER; j++)
			{
				sum += buffer[ DIVIDER * i + j];
			}
			int real_y = (sum / DIVIDER) / 128;
			if (i >= 1) {
				SSD1306_DrawLine(i - 1, prev_y, i, real_y, SSD1306_COLOR_WHITE);
			}
			prev_y = real_y;
		}
	}
}

